// Writes src/licences.ts: the copyright notice of every library and font grail ships, and the full text of each
// licence they use (MIT, ISC, SIL OFL 1.1), read from their own LICENSE files in node_modules. MIT, ISC and the OFL
// all require the notice and the licence text to travel with the app, so the Licences screen shows them in full.
// Run after adding or removing a dependency: node scripts/licences.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const skip = new Set(['@types/react', 'typescript', '@grail/core'])

const licenceFile = (dir) => readdirSync(dir).find((f) => /^licen[cs]e(\.md|\.txt)?$/i.test(f))
const copyrightOf = (text) => (text.match(/^.*copyright.*$/im) || [''])[0].trim()

const notices = []
const texts = {}
for (const name of Object.keys(pkg.dependencies).filter((d) => !skip.has(d)).sort()) {
  const dir = join(root, 'node_modules', ...name.split('/'))
  const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const file = licenceFile(dir)
  const text = file ? readFileSync(join(dir, file), 'utf8') : ''
  const licence = String(meta.license || '').replace(/ AND OFL-1\.1$/, '')
  notices.push({ name, licence, copyright: copyrightOf(text) })
  if (licence === 'MIT' && !texts.MIT && /permission is hereby granted/i.test(text)) {
    texts.MIT = text.slice(text.search(/permission is hereby granted/i)).trim()
  }
  if (licence === 'ISC' && !texts.ISC) texts.ISC = text.slice(text.search(/permission to use/i)).trim()
  // The Google Fonts packages also carry the font's own licence (the font itself is OFL; the package code is MIT).
  const fontLicence = readdirSync(dir).find((f) => f === 'LICENSE_FONT')
  if (fontLicence) {
    const font = readFileSync(join(dir, fontLicence), 'utf8')
    notices.push({ name: `${meta.name.replace('@expo-google-fonts/', '')} (font)`, licence: 'OFL-1.1', copyright: copyrightOf(font) })
    if (!texts['OFL-1.1']) texts['OFL-1.1'] = font.slice(font.search(/this font software is licensed/i)).trim()
  }
}

const out = `// Generated by scripts/licences.mjs from the LICENSE files in node_modules: don't edit by hand.
export type Notice = { name: string; licence: string; copyright: string }
export const NOTICES: Notice[] = ${JSON.stringify(notices, null, 2)}
export const LICENCE_TEXTS: Record<string, string> = ${JSON.stringify(texts, null, 2)}
`
writeFileSync(join(root, 'src', 'licences.ts'), out)
console.log(`${notices.length} notices; licence texts: ${Object.keys(texts).join(', ')}`)
